"""Two-stage fact extraction for the public profile evaluation pipeline.

Stage one is history-only and produces the shared source catalogue. Stage two
receives that immutable catalogue and one profile, then produces profile blocks
and links. FactEvents, public materials and the three headline judgments remain
deterministic Python work.
"""
from __future__ import annotations

from collections.abc import Mapping
import hashlib
import json
from typing import Any

from .blackbox import build_final_request, _final_scores
from .fact_pipeline import (
    FACT_PROTOCOL_VERSION,
    FACT_RELATIONS,
    FACT_STATES,
    CONDITION_TYPES,
    ASSERTION_STATUS,
    IMPORTANCE_VALUES,
    OWNER_VALUES,
    evaluate_public_fact_graph,
    validate_fact_graph,
    _derive_history_withdrawals,
)


HISTORY_STAGE_PROMPT = r"""You are the history-only source fact extractor for a profile evaluation pipeline.

INPUT contains one persona's USER history and no profile. Return exactly one JSON
object with exactly one key: source_blocks. Do not return profile_blocks, links,
events, scores, or the six preprocessing materials.

A source block is one independently assessable proposition stated or clearly
described in USER history. Split compound messages into atomic propositions. Keep
chronology: stage is the stage of the earliest exact evidence message. Preserve
the exact source quote and SID. Do not use any information outside INPUT.

Every source block must have:
  fact_id, stage, text, kind, owner, evidence_strength, importance, state,
  condition_type, condition, evidence, uncertainty.

Use fact_id SF0001, SF0002, ... in stable history order. Allowed values:
kind = fact|preference|habit|goal|episode|state|constraint
owner = user|third_party|authored_payload|fictional_or_roleplay|mixed|uncertain
evidence_strength = explicit|grounded_inference|authored_payload|uncertain
importance = required|optional|excluded|uncertain
state = active|withdrawn|superseded|uncertain
condition_type = decision|context|none|uncertain

Evidence must be a list of objects like:
{"sid":"u12","stage":2,"quote":"exact contiguous substring from u12"}
The quote must be copied character-for-character from the supplied USER message.
Never paraphrase, shorten with ellipses, or invent a quote. If a proposition
cannot be grounded with an exact quote, omit it or mark it uncertain with an
empty evidence list. A decision condition is a clause limiting when a fact
applies; ordinary time, place, or narrative context is not a decision condition.

This source catalogue is profile-independent. It must be determined solely by
the supplied history and must not be tailored to any future or hidden profile.
FactEvents are generated by Python from this catalogue and the history; do not
output them. Return JSON only."""


PROFILE_STAGE_PROMPT = r"""You are the profile projection extractor for a profile evaluation pipeline.

INPUT contains one profile and an immutable source catalogue extracted from the
same persona history. Return exactly one JSON object with exactly these keys:
profile_blocks, coverage, uncertainty.

Do not return source_blocks or events. The source_blocks in INPUT are read-only:
do not edit, merge, split, delete, or create source facts. A profile block is
one independently assessable proposition presented by the supplied profile.
Split compound profile units into atomic blocks but preserve the same unit_id for
all blocks from one profile unit.

Every profile block must have:
  fact_id, profile_id, stage, unit_id, text, owner, assertion_status,
  condition_type, condition, evidence, links, uncertainty.

Use a globally unique profile fact_id such as PF0001, PF0002, ... . The profile
evidence must be an exact substring of the cited profile unit:
{"kind":"profile","profile_id":"...","unit_id":"...","cid":1,
 "span":"exact contiguous substring of that profile unit"}

Every link must reference an existing source_blocks.fact_id exactly. Link shape:
{"fact_id":"SF0001","relation":"equivalent|partial|contradictory|unsupported|overgeneralized|stale|uncertain"}
Do not create a source ID, use a local ID, or link to an absent source block.
If no reliable source relation exists, use links=[] or relation=uncertain; never
guess. Copy source evidence only by referring to the source fact ID; do not
rewrite its quote. The profile owner is the owner asserted by the profile text.

coverage must be {"profiles":{"PROFILE_ID":{"unit_status":{"UNIT_ID":
"covered|empty_control|uncertain"}}}} and must account for every supplied unit.
Return JSON only."""


def _hash(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(",", ":")).encode()).hexdigest()


def build_history_payload(*, persona_id: str, history: Any,
                          model_id: str) -> tuple[dict[str, Any], dict[str, Any]]:
    """Build the history-only request and the normalized request context."""
    # A temporary profile is used only to reuse the public history normalizer;
    # it is deliberately removed from the stage payload.
    request = build_final_request(
        history=history,
        profile={"id": "__history_only__", "stage": 1, "text": "history-only"},
        model_id=model_id,
    )
    payload = {
        "protocol_version": FACT_PROTOCOL_VERSION,
        "stage": "history_source",
        "persona_id": str(persona_id),
        "history": {"messages": request["history"]["messages"]},
        "output_schema": {"source_blocks": "FactBlock[]"},
    }
    payload["history_hash"] = _hash(payload["history"])
    return payload, request


def build_profile_payload(*, persona_id: str, request: Mapping[str, Any],
                          source_blocks: list[dict[str, Any]]) -> dict[str, Any]:
    profile = request["profiles"][0]
    payload = {
        "protocol_version": FACT_PROTOCOL_VERSION,
        "stage": "profile_projection",
        "persona_id": str(persona_id),
        "profile": profile,
        "source_blocks": source_blocks,
        "source_catalogue_hash": _hash(source_blocks),
        "output_schema": {
            "profile_blocks": "FactBlock[]",
            "coverage": "object",
            "uncertainty": "string[] or object[]",
        },
    }
    return payload


def _first_evidence(row: Mapping[str, Any]) -> tuple[str | None, str | None]:
    evidence = row.get("evidence")
    if isinstance(evidence, Mapping):
        return evidence.get("sid"), evidence.get("quote")
    if isinstance(evidence, list):
        for item in evidence:
            if isinstance(item, Mapping) and item.get("sid") and item.get("quote"):
                return item.get("sid"), item.get("quote")
            if isinstance(item, list) and len(item) == 2:
                return item[0], item[1]
    return row.get("sid") or row.get("source_sid"), row.get("quote") or row.get("source_quote")


def _enum(value: Any, allowed: set[Any], fallback: Any) -> Any:
    return value if value in allowed else fallback


def normalize_source_stage(raw: Mapping[str, Any], request: Mapping[str, Any]) -> tuple[list[dict[str, Any]], list[str]]:
    """Normalize source-only output while preserving exact-evidence failures."""
    messages = {row["sid"]: row for row in request["history"]["messages"]}
    rows = raw.get("source_blocks")
    if not isinstance(rows, list):
        raise ValueError("history stage must return source_blocks[]")
    blocks: list[dict[str, Any]] = []
    warnings: list[str] = []
    used: set[str] = set()
    for index, item in enumerate(rows, 1):
        if not isinstance(item, Mapping):
            continue
        sid, quote = _first_evidence(item)
        text = str(item.get("text") or item.get("proposition") or quote or "").strip()
        if not text:
            continue
        fact_id = str(item.get("fact_id") or f"SF{index:04d}")
        if fact_id in used or not fact_id:
            fact_id = f"SF{index:04d}"
        while fact_id in used:
            index += 1
            fact_id = f"SF{index:04d}"
        used.add(fact_id)
        message = messages.get(sid)
        exact = bool(message and isinstance(quote, str) and quote and quote in message["text"])
        evidence = ([{"kind": "source", "sid": sid, "stage": message["stage"], "quote": quote}]
                    if exact else [])
        uncertainty = item.get("uncertainty")
        if not exact:
            reason = "source evidence is not an exact substring of the supplied history"
            uncertainty = f"{uncertainty}; {reason}" if uncertainty else reason
            warnings.append(f"{fact_id}: {reason}")
        condition_type = item.get("condition_type")
        condition_alias = {"D": "decision", "C": "context", "N": "none", "U": "uncertain"}
        condition_type = condition_alias.get(condition_type, condition_type)
        condition_type = _enum(condition_type, {"decision", "context", "none", "uncertain"}, "uncertain")
        condition = item.get("condition")
        if condition_type == "none":
            condition = None
        elif condition is not None:
            condition = str(condition).strip() or None
        state_alias = {"A": "active", "W": "withdrawn", "S": "superseded", "U": "uncertain"}
        state = state_alias.get(item.get("state"), item.get("state"))
        state = _enum(state, FACT_STATES, "uncertain")
        block = {
            "fact_id": fact_id, "origin": "source",
            "stage": int(message["stage"] if message else item.get("stage", 1)),
            "profile_id": None, "unit_id": None, "text": text,
            "kind": _enum(item.get("kind"), {"fact", "preference", "habit", "goal", "episode", "state", "constraint"}, "fact"),
            "owner": _enum(item.get("owner"), OWNER_VALUES, "uncertain"),
            "evidence_strength": _enum(item.get("evidence_strength"), {"explicit", "grounded_inference", "authored_payload", "uncertain"}, "uncertain"),
            "importance": _enum(item.get("importance"), IMPORTANCE_VALUES, "uncertain"),
            "state": state, "assertion_status": "current",
            "condition_type": condition_type, "condition": condition,
            "evidence": evidence, "links": [], "uncertainty": uncertainty,
        }
        blocks.append(block)
    if not blocks:
        raise ValueError("history stage returned no usable source blocks")
    return blocks, warnings


def _profile_unit_text(request: Mapping[str, Any], unit_id: str) -> tuple[int, str]:
    profile = request["profiles"][0]
    for index, unit in enumerate(profile.get("units", []), 1):
        candidate = unit.get("unit_id", unit.get("id", f"C{index}")) if isinstance(unit, Mapping) else f"C{index}"
        candidate = str(candidate)
        if not candidate.startswith(profile["profile_id"] + "/"):
            candidate = f"{profile['profile_id']}/{candidate}"
        if candidate == unit_id:
            return int(unit.get("cid", index) if isinstance(unit, Mapping) else index), str(unit.get("text", "") if isinstance(unit, Mapping) else unit)
    return 0, ""


def normalize_profile_stage(raw: Mapping[str, Any], request: Mapping[str, Any],
                           source_blocks: list[dict[str, Any]]) -> tuple[dict[str, Any], list[str]]:
    profile = request["profiles"][0]
    profile_id = profile["profile_id"]
    source_ids = {row["fact_id"] for row in source_blocks}
    rows = raw.get("profile_blocks")
    if not isinstance(rows, list):
        raise ValueError("profile stage must return profile_blocks[]")
    blocks: list[dict[str, Any]] = []
    warnings: list[str] = []
    used: set[str] = set()
    for index, item in enumerate(rows, 1):
        if not isinstance(item, Mapping):
            continue
        row_profile = str(item.get("profile_id") or profile_id)
        if row_profile != profile_id:
            warnings.append(f"PF{index:04d}: profile_id rewritten to supplied profile")
            row_profile = profile_id
        raw_unit = str(item.get("unit_id") or item.get("cid") or "C1")
        unit_id = raw_unit if raw_unit.startswith(profile_id + "/") else f"{profile_id}/{raw_unit}"
        cid, unit_text = _profile_unit_text(request, unit_id)
        if not cid:
            warnings.append(f"PF{index:04d}: unknown unit_id {unit_id}")
            continue
        text = str(item.get("text") or item.get("proposition") or unit_text).strip()
        if not text:
            continue
        fact_id = str(item.get("fact_id") or f"PF{index:04d}")
        if fact_id in used or fact_id in source_ids:
            fact_id = f"PF{index:04d}"
        while fact_id in used or fact_id in source_ids:
            index += 1
            fact_id = f"PF{index:04d}"
        used.add(fact_id)
        ev = item.get("evidence")
        span = item.get("profile_evidence") or item.get("span")
        if isinstance(ev, Mapping):
            span = span or ev.get("span")
        elif isinstance(ev, list):
            for candidate in ev:
                if isinstance(candidate, Mapping) and candidate.get("span"):
                    span = span or candidate.get("span")
                    break
        span = str(span or text)
        exact = span in unit_text if unit_text else False
        uncertainty = item.get("uncertainty")
        if not exact:
            reason = "profile evidence is not an exact substring of the supplied profile unit"
            span = unit_text
            uncertainty = f"{uncertainty}; {reason}" if uncertainty else reason
            warnings.append(f"{fact_id}: {reason}")
        links = []
        for link in item.get("links", []) or []:
            if not isinstance(link, Mapping):
                continue
            target = link.get("fact_id") or link.get("source_fact_id")
            relation = link.get("relation")
            if target in source_ids and relation in FACT_RELATIONS:
                links.append({"fact_id": target, "relation": relation})
            elif target:
                warnings.append(f"{fact_id}: dropped invalid source link {target}")
        source_by_id = {row["fact_id"]: row for row in source_blocks}
        for link in links:
            source_row = source_by_id.get(link["fact_id"])
            if source_row and (source_row.get("uncertainty") or not source_row.get("evidence")):
                link["relation"] = "uncertain"
                warnings.append(f"{fact_id}: source link downgraded because source evidence is uncertain")
        if not exact:
            links = [{**link, "relation": "uncertain"} for link in links]
        condition_type = {"D": "decision", "C": "context", "N": "none", "U": "uncertain"}.get(item.get("condition_type"), item.get("condition_type"))
        condition_type = _enum(condition_type, CONDITION_TYPES, "uncertain")
        condition = item.get("condition")
        if condition_type == "none":
            condition = None
        elif condition is not None:
            condition = str(condition).strip() or None
        assertion = {"asserted": "current", "withdrawn": "historical"}.get(item.get("assertion_status"), item.get("assertion_status"))
        assertion = _enum(assertion, ASSERTION_STATUS, "uncertain")
        block = {
            "fact_id": fact_id, "origin": "profile", "stage": int(profile["stage"]),
            "profile_id": profile_id, "unit_id": unit_id, "text": text,
            "kind": "fact", "owner": _enum(item.get("owner"), OWNER_VALUES, "uncertain"),
            "evidence_strength": _enum(item.get("evidence_strength"), {"explicit", "grounded_inference", "authored_payload", "uncertain"}, "uncertain"),
            "importance": _enum(item.get("importance"), IMPORTANCE_VALUES, "uncertain"),
            "state": "withdrawn" if assertion == "historical" else "active",
            "assertion_status": assertion, "condition_type": condition_type, "condition": condition,
            "evidence": [{"kind": "profile", "profile_id": profile_id, "unit_id": unit_id,
                          "cid": cid, "span": span}],
            "links": links, "uncertainty": uncertainty,
        }
        if links:
            linked = next((row for row in source_blocks if row["fact_id"] == links[0]["fact_id"]), None)
            if linked:
                block["evidence_strength"] = linked["evidence_strength"]
                block["importance"] = linked["importance"]
        blocks.append(block)
    raw_coverage = raw.get("coverage") if isinstance(raw.get("coverage"), Mapping) else {}
    profile_cov = raw_coverage.get("profiles", {}).get(profile_id, {}) if isinstance(raw_coverage.get("profiles"), Mapping) else {}
    statuses = profile_cov.get("unit_status", {}) if isinstance(profile_cov, Mapping) else {}
    unit_coverage = {}
    for index, unit in enumerate(profile.get("units", []), 1):
        unit_id = str(unit.get("unit_id", unit.get("id", f"C{index}"))) if isinstance(unit, Mapping) else f"C{index}"
        if not unit_id.startswith(profile_id + "/"):
            unit_id = f"{profile_id}/{unit_id}"
        short = unit_id.rsplit("/", 1)[-1]
        status = statuses.get(unit_id, statuses.get(short)) if isinstance(statuses, Mapping) else None
        if status is None:
            status = "covered" if any(row["unit_id"] == unit_id for row in blocks) else "uncertain"
            warnings.append(f"{unit_id}: coverage inferred as {status}")
        status = "complete" if status in {"covered", "complete"} else "empty_control" if status == "empty_control" else "uncertain"
        unit_coverage[unit_id] = {"fact_ids": [row["fact_id"] for row in blocks if row["unit_id"] == unit_id], "status": status}
    graph = {
        "source_blocks": source_blocks, "profile_blocks": blocks,
        "events": [],
        "coverage": {
            "source_messages_total": len(request["history"]["messages"]),
            "source_messages_accounted": len(request["history"]["messages"]),
            "profile_units_total": len(profile.get("units", [])),
            "profile_units_accounted": len(unit_coverage),
            "unit_coverage": unit_coverage,
        },
        "uncertainty": list(raw.get("uncertainty", [])) if isinstance(raw.get("uncertainty"), list) else [],
    }
    return graph, warnings


def finalize_two_stage_graph(source_blocks: list[dict[str, Any]], raw_profile: Mapping[str, Any],
                            request: Mapping[str, Any]) -> tuple[dict[str, Any], list[str]]:
    graph, warnings = normalize_profile_stage(raw_profile, request, source_blocks)
    graph["events"] = _derive_history_withdrawals(graph, request)
    validate_fact_graph(graph, request=request)
    return graph, warnings


def score_two_stage_graph(graph: Mapping[str, Any], request: Mapping[str, Any]) -> dict[str, Any]:
    compiled = evaluate_public_fact_graph(graph, request=request)
    public_tasks = compiled["tasks"]
    return {
        "materials": compiled["materials"],
        "tasks": public_tasks,
        "scores": _final_scores(graph, public_tasks),
        "validation": validate_fact_graph(graph, request=request),
    }


